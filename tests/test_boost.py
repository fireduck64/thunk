class FastWordTokenizer:
    def encode(self, text: str):
        return (text or "").split()

    def decode(self, tokens):
        return " ".join(tokens)


def _load_boost_script_module():
    script_path = Path(__file__).resolve().parents[1] / "scripts" / "boost.py"
    spec = importlib.util.spec_from_file_location("boost_cli", script_path)
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return mod


def _make_mock_streaming_client(recorded_calls: list, label: str, reply_prefix: str = "Summary"):
    class _MockCompletions:
        async def create(self, **kwargs):
            recorded_calls.append({"client": label, "model": kwargs.get("model"), "kwargs": kwargs})

            async def _gen():
                chunk = SimpleNamespace(
                    choices=[
                        SimpleNamespace(
                            delta=SimpleNamespace(
                                content=f"{reply_prefix} from {label} ({kwargs.get('model')})",
                                tool_calls=None,
                            ),
                            finish_reason="stop",
                        )
                    ],
                    usage={"prompt_tokens": 120, "completion_tokens": 12},
                )
                yield chunk

            return _gen()

    return SimpleNamespace(chat=SimpleNamespace(completions=_MockCompletions()))


@pytest.mark.asyncio
async def test_prompt_token_watermark_scales_with_high_watermark(tmp_path, monkeypatch):
    """
    Verifies that raising [memory].high_watermark (e.g. 32000) without explicitly setting
    prompt_token_watermark automatically scales prompt_token_watermark to 1.5x (48000)
    so 25k-token Gemini prompts do not thrash compaction every 2 turns.
    """
    db_path = str(tmp_path / "watermark_test.db")
    tok = FastWordTokenizer()

    import src.components.tiered as tiered_mod

    base_cfg = tiered_mod.load_config()
    patched_cfg = dict(base_cfg)
    patched_cfg["memory"] = {
        "high_watermark": 32000,
        "low_watermark": 16000,
        "max_summarize_tokens": 16000,
        "max_summary_tokens": 4096,
        "db_path": db_path,
    }
    monkeypatch.setattr(tiered_mod, "load_config", lambda: patched_cfg)

    mem = TieredMemoryComponent(db_path=db_path, thread_id="mind", tokenizer=tok)
    try:
        assert mem.prompt_token_watermark == 48000

        agent = AgentCore(thread_id="mind")
        agent.register_component(mem)
        agent.messages = [
            {"role": "system", "content": "sys"},
            *[{"role": "user", "content": f"msg {i}"} for i in range(8)],
        ]
        # 25,000 prompt tokens used to trip the old hardcoded 24,000 watermark; now it must NOT compact
        agent.last_agent_turn_prompt_tokens = 25000
        calls = []
        agent.client = _make_mock_streaming_client(calls, "base")

        await agent.event_bus.publish("context_window_check", {"agent": agent})
        assert len(calls) == 0
        assert len(agent.messages) == 9
    finally:
        mem._lock_file.close()


@pytest.mark.asyncio
async def test_boost_compaction_sweep_authors_summary_on_boost_model_before_stepping_down(tmp_path):
    """
    Verifies:
    1. Multi-chunk compaction inside a single context_window_check counts as 1 compaction sweep.
    2. While remaining_compactions=1, the compaction summary itself is generated by the boost model
       (gemini-4-neon), and immediately after the sweep completes, AgentCore steps back down to
       its base model (gemma4:31b) and appends a [System Notice].
    """
    db_path = str(tmp_path / "boost_compaction.db")
    tok = FastWordTokenizer()

    mem = TieredMemoryComponent(db_path=db_path, thread_id="mind", tokenizer=tok)
    # Force multi-chunk sweep inside a single context_window_check:
    # high_watermark=60, low_watermark=15, max_summarize_tokens=25 -> requires 2 chunks in 1 sweep
    mem.high_watermark = 60
    mem.low_watermark = 15
    mem.max_summarize_tokens = 25

    try:
        calls = []
        agent = AgentCore(thread_id="mind")
        agent.client = _make_mock_streaming_client(calls, "base_local")
        agent.base_client = agent.client
        agent._boost_client = _make_mock_streaming_client(calls, "boost_cloud")
        agent._boost_exec_location = "cloud"
        agent.register_component(mem)

        agent.messages = [{"role": "system", "content": "You are Thunk."}]
        for idx in range(6):
            msg = {"role": "user", "content": ("alpha beta gamma delta epsilon " * 3).strip() + f" #{idx}"}
            agent.messages.append(msg)
            await mem.on_event("message_added", {"message": msg})

        res = agent.activate_boost(compactions=1, reason="untangle loop", triggered_by="test")
        assert res["ok"] is True
        assert agent.is_boosted is True
        assert agent.model == "gemini-4-neon"
        assert agent.exec_location == "cloud"
        assert agent.boost_state["remaining_compactions"] == 1
        assert agent.boost_state["remaining_turns"] == 0

        # Trigger context_window_check -> should compress >=2 chunks in ONE sweep using boost_cloud,
        # then step down to base_local!
        await agent.event_bus.publish("context_window_check", {"agent": agent})

        assert len(calls) >= 2
        assert all(c["client"] == "boost_cloud" and c["model"] == "gemini-4-neon" for c in calls)
        assert "boost_cloud (gemini-4-neon)" in mem._get_core_summary()

        # Stepped back down to base model right after writing the Core Summary
        assert agent.is_boosted is False
        assert agent.model == "gemma4:31b"
        assert agent.client is agent.base_client
        assert mem.get_boost_state() is None
        assert any(
            "Boost Mode ended on thread 'mind' (compaction budget reached" in (m.get("content") or "")
            for m in agent.messages
        )
    finally:
        mem._lock_file.close()


@pytest.mark.asyncio
async def test_boost_turn_countdown_persistence_and_self_trigger_tool(tmp_path):
    """
    Verifies:
    1. Calling activate_boost_mode via SystemComponent switches model without wasting a boost turn on the triggering turn.
    2. Boost state persists to memory.db and restores cleanly on a fresh AgentCore startup.
    3. Completing remaining_turns steps back down to base model and clears persisted boost_state.
    """
    db_path = str(tmp_path / "boost_turns.db")
    tok = FastWordTokenizer()
    mem = TieredMemoryComponent(db_path=db_path, thread_id="mind", tokenizer=tok)

    try:
        calls = []
        agent = AgentCore(thread_id="mind")
        agent.client = _make_mock_streaming_client(calls, "base_local")
        agent.base_client = agent.client
        agent._boost_client = _make_mock_streaming_client(calls, "boost_cloud")
        agent._boost_exec_location = "cloud"

        sys_comp = SystemComponent()
        agent.register_component(sys_comp)
        agent.register_component(mem)
        agent._build_tools()
        assert "activate_boost_mode" in agent.tool_map
        assert "activate_boost_mode" in sys_comp.get_system_prompt_addition()

        agent.messages = [{"role": "system", "content": "sys"}, {"role": "user", "content": "hi"}]

        # Simulate a base-model turn where the agent calls activate_boost_mode
        turn_boost_seq = agent._boost_seq if agent.is_boosted else None
        assert turn_boost_seq is None

        tool_out = await agent.execute_tool(
            "activate_boost_mode",
            json.dumps({"reason": "stuck on toaster physics"}),
        )
        assert "Boost Mode ACTIVATED on thread 'mind' -> gemini-4-neon" in tool_out
        assert agent.is_boosted is True
        assert agent.boost_state["remaining_compactions"] == 3
        assert agent.boost_state["remaining_turns"] == 75

        # End of the triggering base turn must NOT decrement remaining_turns
        if turn_boost_seq is not None:
            await agent._record_boost_turn_completed(expected_seq=turn_boost_seq)
        assert agent.boost_state["remaining_turns"] == 75

        # Override to 2 turns so we can test persistence across restart after 1 turn
        agent.activate_boost(turns=2, reason="two-turn sprint", triggered_by="agent:mind")
        seq = agent._boost_seq
        msg1 = await agent._call_llm_with_retries(agent._prepare_llm_messages())
        assert "boost_cloud" in (msg1.content or "")
        await agent._record_boost_turn_completed(expected_seq=seq)
        assert agent.is_boosted is True
        assert agent.boost_state["remaining_turns"] == 1

        saved = mem.get_boost_state()
        assert saved is not None and saved["remaining_turns"] == 1
    finally:
        mem._lock_file.close()

    # Simulate process restart on the same memory.db -> boost state restores with remaining_turns == 1
    mem2 = TieredMemoryComponent(db_path=db_path, thread_id="mind", tokenizer=tok)
    try:
        calls2 = []
        agent2 = AgentCore(thread_id="mind")
        agent2.client = _make_mock_streaming_client(calls2, "base_local_2")
        agent2.base_client = agent2.client
        agent2._boost_client = _make_mock_streaming_client(calls2, "boost_cloud_2")
        agent2._boost_exec_location = "cloud"
        agent2.register_component(mem2)

        agent2.messages = [{"role": "system", "content": "sys"}]
        await agent2.event_bus.publish("agent_started", {"agent": agent2})

        assert agent2.is_boosted is True
        assert agent2.model == "gemini-4-neon"
        assert agent2.boost_state["remaining_turns"] == 1
        startup_str = agent2.build_startup_message()
        assert "Main LLM: gemini-4-neon" in startup_str
        assert "[Boost Mode ACTIVE" in startup_str

        # Run the final 1 boosted turn -> steps back down to gemma4:31b and deletes DB key
        seq2 = agent2._boost_seq
        await agent2.add_message("user", startup_str)
        await agent2._call_llm_with_retries(agent2._prepare_llm_messages())
        await agent2._record_boost_turn_completed(expected_seq=seq2)

        assert agent2.is_boosted is False
        assert agent2.model == "gemma4:31b"
        assert mem2.get_boost_state() is None
    finally:
        mem2._lock_file.close()


@pytest.mark.asyncio
async def test_cross_thread_tool_and_mqtt_cli_boost_routing(tmp_path):
    """
    Verifies:
    1. scripts/boost.py payload builder defaults to thread='all' and supports --turns, --compactions, --off, --status.
    2. MQTTAdapter routes '{"control": "boost"}' across sibling threads via ThreadRegistry, waking sleeping mind thread.
    3. SystemComponent.activate_boost_mode(target_thread='mind') allows social to boost mind directly.
    """
    boost_cli = _load_boost_script_module()
    parser = boost_cli.build_arg_parser()

    default_payload = boost_cli.build_boost_payload(parser.parse_args([]))
    assert default_payload == {"control": "boost", "action": "on", "thread": "all", "wake": True}

    custom_payload = boost_cli.build_boost_payload(
        parser.parse_args(["--thread", "mind", "--turns", "25", "--reason", "cron nudge"])
    )
    assert custom_payload == {
        "control": "boost",
        "action": "on",
        "thread": "mind",
        "wake": True,
        "reason": "cron nudge",
        "turns": 25,
    }

    off_payload = boost_cli.build_boost_payload(parser.parse_args(["--off", "--no-wake"]))
    assert off_payload == {"control": "boost", "action": "off", "thread": "all", "wake": False}

    # Wire up multi-thread social + mind with ThreadRegistry and MQTTAdapter on social
    db_path = str(tmp_path / "mt_boost.db")
    tok = FastWordTokenizer()
    social_mem = TieredMemoryComponent(db_path=db_path, thread_id="social", tokenizer=tok)
    mind_mem = TieredMemoryComponent(db_path=db_path, thread_id="mind", tokenizer=tok)

    try:
        registry = ThreadRegistry()
        social = AgentCore(thread_id="social")
        mind = AgentCore(thread_id="mind")
        for core in (social, mind):
            core._boost_client = _make_mock_streaming_client([], "boost")
            core._boost_exec_location = "cloud"

        registry.register_thread("social", "Social voice", core=social)
        registry.register_thread("mind", "Deep mind", core=mind)

        social.register_component(ThreadPresenceComponent(registry=registry, thread_id="social", role="Social voice"))
        social.register_component(SystemComponent())
        social.register_component(social_mem)
        social._build_tools()

        mind.register_component(ThreadPresenceComponent(registry=registry, thread_id="mind", role="Deep mind"))
        mind.register_component(SystemComponent())
        mind.register_component(mind_mem)
        mind._build_tools()

        # Both threads start suspended on base model
        social.suspended.clear()
        mind.suspended.clear()
        mqtt = MQTTAdapter(social)

        # 1. Default CLI payload ("thread": "all") over MQTT inbox boosts BOTH social and mind and wakes both
        await mqtt._handle_message(mqtt.inbox_topic, json.dumps(default_payload))
        assert social.is_boosted is True
        assert mind.is_boosted is True
        assert social.suspended.is_set() is True
        assert mind.suspended.is_set() is True
        mind_notice = await mind.inbox.get()
        assert "[System Notice] Boost Mode ACTIVATED on thread 'mind'" in mind_notice
        social_notice = await social.inbox.get()
        assert "[System Notice] Boost Mode ACTIVATED on thread 'social'" in social_notice

        # Verify ./scripts/boost.py --status reads both active threads from memory.db in read-only mode
        tmp_cfg = tmp_path / "status_cfg.toml"
        tmp_cfg.write_text(
            f'[agent]\nname = "Thunk"\n[memory]\ndb_path = "{db_path}"\n[boost]\nenabled = true\nmodel_name = "gemini-4-neon"\n',
            encoding="utf-8",
        )
        proc = subprocess.run(
            [sys.executable, "scripts/boost.py", "-c", str(tmp_cfg), "--status"],
            capture_output=True,
            text=True,
            check=True,
        )
        assert "thread='mind'" in proc.stdout
        assert "thread='social'" in proc.stdout

        # 2. MQTT --off cancels boost on both threads
        await mqtt._handle_message(mqtt.inbox_topic, json.dumps(off_payload))
        assert social.is_boosted is False
        assert mind.is_boosted is False

        # 3. social uses activate_boost_mode(target_thread='mind') to boost ONLY mind and wake it
        mind.suspended.clear()
        while not mind.inbox.empty():
            await mind.inbox.get()

        res_cross = await social.execute_tool(
            "activate_boost_mode",
            json.dumps({"reason": "Operator asked mind to boost", "thread": "mind"}),
        )
        assert "thread 'mind'" in res_cross
        assert social.is_boosted is False
        assert mind.is_boosted is True
        assert mind.suspended.is_set() is True
        woken_notice = await mind.inbox.get()
        assert "triggered_by: agent:social" in woken_notice
    finally:
        social_mem._lock_file.close()
        mind_mem._lock_file.close()
